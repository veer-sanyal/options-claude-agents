#!/usr/bin/env bash
# One-time setup: create the environment + the 5 subagents + the coordinator + the
# portfolio memory store, from the version-controlled YAML. Control plane = ant
# CLI; data plane (sessions) = run_session.py. Re-run only when the YAML changes
# (use `ant beta:agents update` in CI rather than re-create, to preserve version
# history).
#
# COORDINATOR VERSION-PIN GOTCHA: the coordinator snapshots its subagent roster
# at create/update time and pins each to the version resolved then — later updates
# to a subagent do NOT propagate. After ANY subagent change you must also update
# the coordinator (re-run its `ant beta:agents update`) or it keeps delegating to
# the stale version. This script re-creates everything together so it's consistent
# here; the gotcha bites the incremental `update` path (CI). Keep them in lockstep.
#
# Prereqs:
#   - ant CLI installed and authed (see shared anthropic-cli docs)
#   - envsubst available (gettext)
#   - export these before running:
#       SKILL_ID           the tech-options-framework skill id (upload it first — see README)
#       BROKERAGE_MCP_URL  your TradeStation MCP endpoint
set -euo pipefail

cd "$(dirname "$0")/.."   # options-agents/

: "${SKILL_ID:?set SKILL_ID (upload the skill first — see README §Skill)}"
: "${BROKERAGE_MCP_URL:?set BROKERAGE_MCP_URL (your TradeStation MCP endpoint)}"

mk() {  # mk <yaml-file> -> prints the created agent id
  envsubst < "$1" | ant beta:agents create --transform id -r
}

echo "Creating environment..."
ENV_ID=$(ant beta:environments create \
  < environments/options-cloud.environment.yaml --transform id -r)
echo "  ENV_ID=$ENV_ID"

echo "Creating subagents..."
export POSITION_WATCHER_ID=$(mk agents/position-watcher.agent.yaml)
export CATALYST_MONITOR_ID=$(mk agents/catalyst-monitor.agent.yaml)
export QUALITATIVE_RESEARCHER_ID=$(mk agents/qualitative-researcher.agent.yaml)
export STRATEGY_STRUCTURER_ID=$(mk agents/strategy-structurer.agent.yaml)
export PATTERN_REVIEWER_ID=$(mk agents/pattern-reviewer.agent.yaml)
echo "  watcher=$POSITION_WATCHER_ID catalyst=$CATALYST_MONITOR_ID"
echo "  research=$QUALITATIVE_RESEARCHER_ID structurer=$STRATEGY_STRUCTURER_ID reviewer=$PATTERN_REVIEWER_ID"

echo "Creating coordinator (with subagent roster, pinned to the versions above)..."
COORDINATOR_ID=$(mk agents/coordinator.agent.yaml)
echo "  COORDINATOR_ID=$COORDINATOR_ID"

echo "Creating / seeding the portfolio memory store..."
# Persisted here so run_session.py reuses it every run; otherwise portfolio state
# and the drift log reset each run. init_memory.py reuses MEMORY_STORE_ID if it's
# already exported, so re-running setup.sh won't orphan a store or wipe state.
MEMORY_STORE_ID=$(python scripts/init_memory.py --quiet)
echo "  MEMORY_STORE_ID=$MEMORY_STORE_ID"

cat > .ids.env <<EOF
# Generated by setup.sh — source this before run_session.py. Do not commit.
ENV_ID=$ENV_ID
COORDINATOR_ID=$COORDINATOR_ID
POSITION_WATCHER_ID=$POSITION_WATCHER_ID
CATALYST_MONITOR_ID=$CATALYST_MONITOR_ID
QUALITATIVE_RESEARCHER_ID=$QUALITATIVE_RESEARCHER_ID
STRATEGY_STRUCTURER_ID=$STRATEGY_STRUCTURER_ID
PATTERN_REVIEWER_ID=$PATTERN_REVIEWER_ID
MEMORY_STORE_ID=$MEMORY_STORE_ID
SKILL_ID=$SKILL_ID
BROKERAGE_MCP_URL=$BROKERAGE_MCP_URL
EOF
echo "Wrote .ids.env — source it before running run_session.py."
echo
echo "Reminder: if you later \`ant beta:agents update\` a subagent, also update the"
echo "coordinator — it pins the subagent versions resolved at its own create/update"
echo "time and will keep delegating to the stale version otherwise."
